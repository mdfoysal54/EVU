from __future__ import annotations

from dataclasses import asdict, dataclass, field
from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Optional
from uuid import uuid4


def utc_now() -> datetime:
    return datetime.now(timezone.utc)


class ExperienceStatus(str, Enum):
    RUNNING = "running"
    SUCCESS = "success"
    FAILED = "failed"
    CANCELLED = "cancelled"
    PARTIAL = "partial"


class EventType(str, Enum):
    START = "start"
    OBSERVATION = "observation"
    THOUGHT = "thought"
    ACTION = "action"
    TOOL_CALL = "tool_call"
    TOOL_RESULT = "tool_result"
    MODEL_CALL = "model_call"
    MODEL_RESULT = "model_result"
    VERIFICATION = "verification"
    ERROR = "error"
    CHECKPOINT = "checkpoint"
    FINISH = "finish"


@dataclass
class ExperienceEvent:
    """
    One event in an EVU agent trajectory.

    This is intentionally provider-agnostic.
    """

    event_type: EventType | str
    name: str = ""

    payload: Any = None
    input_data: Any = None
    output_data: Any = None

    metadata: Dict[str, Any] = field(
        default_factory=dict
    )

    timestamp: datetime = field(
        default_factory=utc_now
    )

    event_id: str = field(
        default_factory=lambda: str(uuid4())
    )

    sequence: int = 0

    def to_dict(self) -> Dict[str, Any]:
        data = asdict(self)

        data["event_type"] = str(
            self.event_type.value
            if isinstance(self.event_type, EventType)
            else self.event_type
        )

        data["timestamp"] = self.timestamp.isoformat()

        return data


@dataclass
class Experience:
    """
    Complete reusable experience generated by an agent run.
    """

    experience_id: str = field(
        default_factory=lambda: str(uuid4())
    )

    task: str = ""

    agent_id: Optional[str] = None
    model_id: Optional[str] = None

    status: ExperienceStatus = (
        ExperienceStatus.RUNNING
    )

    events: List[ExperienceEvent] = field(
        default_factory=list
    )

    input_data: Dict[str, Any] = field(
        default_factory=dict
    )

    output_data: Dict[str, Any] = field(
        default_factory=dict
    )

    metadata: Dict[str, Any] = field(
        default_factory=dict
    )

    started_at: datetime = field(
        default_factory=utc_now
    )

    finished_at: Optional[datetime] = None

    def add_event(
        self,
        event: ExperienceEvent,
    ) -> ExperienceEvent:
        event.sequence = len(self.events)
        self.events.append(event)
        return event

    def finish(
        self,
        status: ExperienceStatus,
        output_data: Optional[
            Dict[str, Any]
        ] = None,
    ) -> None:

        self.status = status
        self.finished_at = utc_now()

        if output_data is not None:
            self.output_data = output_data

    @property
    def duration_seconds(self) -> Optional[float]:
        if self.finished_at is None:
            return None

        return (
            self.finished_at
            - self.started_at
        ).total_seconds()

    def to_dict(self) -> Dict[str, Any]:
        return {
            "experience_id": self.experience_id,
            "task": self.task,
            "agent_id": self.agent_id,
            "model_id": self.model_id,
            "status": self.status.value,
            "events": [
                event.to_dict()
                for event in self.events
            ],
            "input_data": self.input_data,
            "output_data": self.output_data,
            "metadata": self.metadata,
            "started_at": self.started_at.isoformat(),
            "finished_at": (
                self.finished_at.isoformat()
                if self.finished_at
                else None
            ),
            "duration_seconds": self.duration_seconds,
        }


@dataclass
class ExperienceFilter:
    """
    Search criteria for collected experiences.
    """

    agent_id: Optional[str] = None
    model_id: Optional[str] = None
    status: Optional[
        ExperienceStatus
    ] = None

    task_contains: Optional[str] = None

    metadata: Dict[str, Any] = field(
        default_factory=dict
    )

    limit: Optional[int] = None


@dataclass
class ExperienceSummary:
    experience_id: str
    task: str
    status: str

    event_count: int

    agent_id: Optional[str]
    model_id: Optional[str]

    duration_seconds: Optional[float]

    success: bool

    metadata: Dict[str, Any] = field(
        default_factory=dict
    )

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)